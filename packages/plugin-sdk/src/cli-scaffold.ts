// ── getScaffoldConfig ─────────────────────────────────────────────────────────

/**
 * Return the scaffold configuration for a given template ID.
 * Throws if an unknown template ID is provided.
 *
 * Повертає конфігурацію шаблону або кидає помилку для невідомого ID.
 */
export function getScaffoldConfig(template: ScaffoldTemplateId): ScaffoldTemplate {
  const config = SCAFFOLD_TEMPLATES[template];
  if (!config) {
    throw new Error(
      `[cli-scaffold] Unknown template "${template}". ` +
        `Valid options: ${Object.keys(SCAFFOLD_TEMPLATES).join(", ")}`,
    );
  }
  return config;
}

/** All available scaffold templates as an ordered array. */
export const ALL_SCAFFOLD_TEMPLATES: ScaffoldTemplate[] = Object.values(SCAFFOLD_TEMPLATES);
