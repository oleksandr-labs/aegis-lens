// ── ScaffoldTemplate ──────────────────────────────────────────────────────────

export type ScaffoldTemplateId = "data-layer" | "widget" | "ai-tool" | "exporter";

/**
 * Configuration for a single scaffold template.
 *
 * Конфігурація одного шаблону для scaffold.
 */
