/**
 * Alert System Config — multi-channel alert delivery with rule engine.
 *
 * Users define rules (keyword, entity, AOI, threshold, AI suggestion).
 * Alerts are delivered over configurable channels with deduplification
 * and quiet-hour support.
 *
 * Система алертів: правила + AI-пропозиції + багатоканальна доставка.
 */

'use server';

// ── Channels ──────────────────────────────────────────────────────────────────

export type AlertChannel = 'email' | 'telegram' | 'slack' | 'discord' | 'webhook' | 'sms';

export const ALERT_CHANNELS: AlertChannel[] = [
  'email', 'telegram', 'slack', 'discord', 'webhook', 'sms',
];

// ── Rule types ────────────────────────────────────────────────────────────────

export type AlertRuleType =
  | 'keyword'
  | 'entity'
  | 'aoi'
  | 'threshold'
  | 'ai-suggestion';

export const ALERT_RULE_TYPES: AlertRuleType[] = [
  'keyword', 'entity', 'aoi', 'threshold', 'ai-suggestion',
];

// ── Rule shape ────────────────────────────────────────────────────────────────

export interface AlertRule {
  id: string;
  userId: string;
  type: AlertRuleType;
  /** Rule-specific parameters (keywords[], entityId, aoiId, metric+threshold) */
  params: Record<string, unknown>;
  channels: AlertChannel[];
  /** Whether the rule is active — Чи активне правило */
  enabled: boolean;
  /** Minimum danger score to trigger — Мін. danger score для тригера */
  minDangerScore: number;
  /** Minimum confidence score to trigger — Мін. confidence для тригера */
  minConfidence: number;
  /** Deduplification window in minutes — Вікно дедублікації (хв) */
  dedupWindowMinutes: number;
  /** Quiet hours UTC (e.g. [22, 6]) — Тихий час UTC */
  quietHoursUtc: [number, number] | null;
}

// ── Channel configs ───────────────────────────────────────────────────────────

export interface ChannelConfig {
  channel: AlertChannel;
  /** Max alerts per user per hour — Макс. алертів на користувача за годину */
  rateLimitPerHour: number;
  /** Auth/credential type — Тип авторизації */
  authType: string;
  /** Whether rich HTML/markdown is supported — Чи підтримується форматування */
  richFormat: boolean;
  /** Required tier — Необхідний tier */
  requiredTier: string;
}

