// ── System config ─────────────────────────────────────────────────────────────

export interface AlertSystemConfig {
  channels: AlertChannel[];
  ruleTypes: AlertRuleType[];
  channelConfigs: Record<AlertChannel, ChannelConfig>;
  /** Max rules per user — Макс. правил на користувача */
  maxRulesPerUser: number;
  /** Max channels per rule — Макс. каналів на правило */
  maxChannelsPerRule: number;
  /** Global deduplification TTL in minutes — Глобальний TTL дедублікації (хв) */
  globalDedupTtlMinutes: number;
}

